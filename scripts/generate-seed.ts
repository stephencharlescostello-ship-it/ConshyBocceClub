type Frame = { team: "home" | "away" | null; points: number; hangers: number; weights: number[] };
function simulateGame(sh: number, sa: number, f: Format): { home: number; away: number; frames: Frame[] } {
  let home = 0, away = 0;
  const frames: Frame[] = [];
  while (!isGameOver(home, away, f)) {
    const r = rng();
    if (r < 0.08) { frames.push({ team: null, points: 0, hangers: 0, weights: [] }); continue; }
    const homeScores = rng() < sh / (sh + sa);
    const weights: number[] = [];
    const count = rng() < 0.55 ? 1 : rng() < 0.7 ? 2 : rng() < 0.8 ? 3 : 4;
    for (let i = 0; i < count; i++) weights.push(rng() < 0.12 ? f.hanger_points : pick(f.zones));
    const points = weights.reduce((a, b) => a + b, 0);
    frames.push({ team: homeScores ? "home" : "away", points, hangers: weights.filter((w) => w === f.hanger_points).length, weights });
    if (homeScores) home += points; else away += points;
  }
  return { home, away, frames };
}
function quickGame(sh: number, sa: number, f: Format) {
  const homeWins = rng() < sh / (sh + sa);
  const loser = Math.min(f.target_score - 1, Math.floor(Math.abs(rng() + rng() - 1) * f.target_score));
  return homeWins ? { home: f.target_score, away: loser } : { home: loser, away: f.target_score };
}
